const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sources = ['shared/sample-pack.js', 'shared/match.js', 'extension/background.js'];
const output = path.join(root, 'extension/background.bundle.js');

function buildBackground() {
  const sections = sources.map(file => `// Source: ${file}\n` + fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n').trimEnd());
  return '// Generated by npm run build. Do not edit this file directly.\n' +
    '// All worker dependencies are embedded; no runtime subscript fetches.\n' +
    "(() => {\n'use strict';\n\n" + sections.join('\n;\n\n') + '\n})();\n';
}

if (require.main === module) {
  const expected = buildBackground();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== expected) { console.error('Background bundle is missing or outdated. Run npm run build.'); process.exitCode = 1; }
    else console.log('Background bundle is up to date.');
  } else { fs.writeFileSync(output, expected); console.log('Built extension/background.bundle.js'); }
}

module.exports = { buildBackground };
